"""Build dist/places.js for Where in the World.

  python3 tools/build-places.py

Joins tools/places-meta.json (what fetch-places.py downloaded: file, artist, licence, source) with
tools/places-text.json (hand-written title, alt, clue and story per id). Ids without text are skipped
and listed, so a photo is never shipped without its clue and story.
"""
import json, pathlib, re
root = pathlib.Path(__file__).resolve().parent.parent
meta = json.loads((root / 'tools/places-meta.json').read_text())
text = json.loads((root / 'tools/places-text.json').read_text())
out, missing = [], []
for pid, m in meta.items():
    if pid.startswith('_'): continue
    t = text.get(pid)
    if not t or t.get('skip'): missing.append(pid); continue
    artist = re.sub(r'\s+', ' ', m['artist']).strip() or 'Unknown photographer'
    out.append({'id': pid, 'image': f'places/{pid}.jpg', 'level': m['level'], 'country': t.get('country', m['country']),
                'title': t['title'], 'alt': t['alt'], 'clue': t['clue'], 'story': t['story'],
                'credit': f"{artist[:80]} / Wikimedia Commons", 'licence': m['licence'], 'licenseUrl': m['licenseUrl'], 'source': m['source']})
out.sort(key=lambda p: (p['level'], p['id']))
(root / 'dist/places.js').write_text('/* Generated by tools/build-places.py — edit tools/places-text.json instead. */\nconst PLACES=' + json.dumps(out, ensure_ascii=False) + ';\n')
print(f'{len(out)} places', [sum(p["level"] == l for p in out) for l in range(3)], 'skipped:', missing)
